-- Private server-side store used by backend/server.py when DATABASE_URL is set.
-- This is intentionally not exposed through the Supabase Data API.
create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

create table if not exists private.users (
  id text primary key,
  email text not null unique,
  name text not null,
  role text not null,
  password_hash text not null,
  otp_secret text not null,
  roll_number text not null,
  program text not null,
  year integer not null,
  hostel integer not null default 0,
  active integer not null default 1,
  created_at text not null
);

create table if not exists private.sessions (
  id text primary key,
  user_id text not null references private.users(id),
  token_hash text not null unique,
  device text not null,
  created_at text not null,
  last_seen text not null,
  expires_at bigint not null,
  revoked integer not null default 0
);
create index if not exists private_sessions_user_active_idx on private.sessions(user_id, expires_at) where revoked = 0;

create table if not exists private.consents (
  user_id text not null references private.users(id),
  service_id text not null,
  granted integer not null,
  updated_at text not null,
  primary key (user_id, service_id)
);

create table if not exists private.passes (
  jti_hash text primary key,
  user_id text not null references private.users(id),
  expires_at bigint not null,
  used integer not null default 0
);

create table if not exists private.audit (
  id bigint generated by default as identity primary key,
  created_at text not null,
  actor text not null,
  action text not null,
  target text not null,
  service text not null,
  details text not null,
  previous_hash text not null,
  entry_hash text not null
);

create table if not exists private.recovery (
  id text primary key,
  user_id text not null references private.users(id),
  code_hash text not null,
  expires_at bigint not null,
  cooling_until bigint not null,
  used integer not null default 0
);

create table if not exists private.backup_codes (
  user_id text not null references private.users(id),
  code_hash text not null,
  used integer not null default 0,
  primary key (user_id, code_hash)
);

create table if not exists private.login_rate_limits (
  identifier_hash text primary key,
  failures integer not null default 0,
  window_started_at bigint not null,
  locked_until bigint not null default 0,
  updated_at bigint not null
);

revoke all on all tables in schema private from public, anon, authenticated;
grant usage on schema private to postgres;
grant all on all tables in schema private to postgres;
grant usage, select on all sequences in schema private to postgres;
alter default privileges in schema private revoke all on tables from public, anon, authenticated;

-- Belt-and-suspenders protection: the server database owner can use these tables,
-- but even accidental API grants cannot expose rows to browser roles.
alter table private.users enable row level security;
alter table private.sessions enable row level security;
alter table private.consents enable row level security;
alter table private.passes enable row level security;
alter table private.audit enable row level security;
alter table private.recovery enable row level security;
alter table private.backup_codes enable row level security;
alter table private.login_rate_limits enable row level security;

create policy "backend only users" on private.users for all to anon, authenticated using (false) with check (false);
create policy "backend only sessions" on private.sessions for all to anon, authenticated using (false) with check (false);
create policy "backend only consents" on private.consents for all to anon, authenticated using (false) with check (false);
create policy "backend only passes" on private.passes for all to anon, authenticated using (false) with check (false);
create policy "backend only audit" on private.audit for all to anon, authenticated using (false) with check (false);
create policy "backend only recovery" on private.recovery for all to anon, authenticated using (false) with check (false);
create policy "backend only backup codes" on private.backup_codes for all to anon, authenticated using (false) with check (false);
create policy "backend only login limits" on private.login_rate_limits for all to anon, authenticated using (false) with check (false);
